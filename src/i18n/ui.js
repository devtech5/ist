/** Remplace les jetons {cle} d'un libellé. */
export function remplir(texte, valeurs) {
  return Object.entries(valeurs).reduce(
    (accumulateur, [cle, valeur]) => accumulateur.replaceAll(`{${cle}}`, String(valeur)),
    texte
  );
}
